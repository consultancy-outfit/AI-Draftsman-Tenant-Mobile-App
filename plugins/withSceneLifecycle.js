/**
 * Moves the iOS app onto the UIScene life cycle.
 *
 * Apps linked against the iOS 27 SDK (Xcode 27+) are stopped at launch with
 * EXC_BREAKPOINT if they still create their window in
 * application(_:didFinishLaunchingWithOptions:). Expo SDK 54's AppDelegate
 * template does exactly that, so this plugin:
 *
 *   1. declares a single-window scene manifest in Info.plist,
 *   2. removes the window / startReactNative block from AppDelegate.swift,
 *   3. adds SceneDelegate.swift, which creates the window for the scene,
 *      starts React Native in it, and forwards deep links / universal links
 *      to the AppDelegate's existing handlers (Expo + RCTLinkingManager).
 *
 * `ios/` is generated and git-ignored, so this re-applies on every prebuild
 * and EAS build. Drop it once the app is on an Expo SDK whose template
 * already uses scenes.
 */
const fs = require('fs');
const path = require('path');
const {
  withInfoPlist,
  withAppDelegate,
  withXcodeProject,
  IOSConfig,
} = require('@expo/config-plugins');

const SCENE_DELEGATE = `import UIKit
import React

/*
 * Generated by plugins/withSceneLifecycle.js — edit the plugin, not this file.
 * Owns the app window under the UIScene life cycle; React Native itself is
 * still set up once in AppDelegate.
 */
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard let windowScene = scene as? UIWindowScene,
          let appDelegate = UIApplication.shared.delegate as? AppDelegate,
          let factory = appDelegate.reactNativeFactory else { return }

    let window = UIWindow(windowScene: windowScene)
    self.window = window
    // Code that still reads the app delegate's window keeps working.
    appDelegate.window = window

    // A cold-start deep link arrives here instead of in launchOptions;
    // pass it on so Linking.getInitialURL() still sees it.
    var launchOptions: [UIApplication.LaunchOptionsKey: Any] = [:]
    if let url = connectionOptions.urlContexts.first?.url {
      launchOptions[.url] = url
    }

    factory.startReactNative(
      withModuleName: "main",
      in: window,
      launchOptions: launchOptions)

    if let activity = connectionOptions.userActivities.first {
      self.scene(scene, continue: activity)
    }
  }

  // Deep links while the app is running.
  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    guard let context = URLContexts.first,
          let delegate = UIApplication.shared.delegate else { return }
    var options: [UIApplication.OpenURLOptionsKey: Any] = [:]
    if let source = context.options.sourceApplication {
      options[.sourceApplication] = source
    }
    if let annotation = context.options.annotation {
      options[.annotation] = annotation
    }
    options[.openInPlace] = context.options.openInPlace
    _ = delegate.application?(UIApplication.shared, open: context.url, options: options)
  }

  // Universal links.
  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    _ = UIApplication.shared.delegate?.application?(
      UIApplication.shared,
      continue: userActivity,
      restorationHandler: { _ in })
  }
}
`;

const WINDOW_BLOCK =
  /#if os\(iOS\) \|\| os\(tvOS\)\s*\n\s*window = UIWindow\(frame: UIScreen\.main\.bounds\)\s*\n\s*factory\.startReactNative\([\s\S]*?\)\s*\n#endif\n/;

const withSceneManifest = (config) =>
  withInfoPlist(config, (cfg) => {
    cfg.modResults.UIApplicationSceneManifest = {
      UIApplicationSupportsMultipleScenes: false,
      UISceneConfigurations: {
        UIWindowSceneSessionRoleApplication: [
          {
            UISceneConfigurationName: 'Default Configuration',
            UISceneDelegateClassName: '$(PRODUCT_MODULE_NAME).SceneDelegate',
          },
        ],
      },
    };
    return cfg;
  });

const withAppDelegateWithoutWindow = (config) =>
  withAppDelegate(config, (cfg) => {
    if (cfg.modResults.language !== 'swift') {
      throw new Error('withSceneLifecycle: expected a Swift AppDelegate');
    }
    let contents = cfg.modResults.contents;
    if (!contents.includes('withSceneLifecycle')) {
      if (!WINDOW_BLOCK.test(contents)) {
        throw new Error(
          'withSceneLifecycle: could not find the window/startReactNative block in AppDelegate.swift'
        );
      }
      contents = contents.replace(
        WINDOW_BLOCK,
        '    // Window + startReactNative live in SceneDelegate (withSceneLifecycle).\n'
      );
    }
    cfg.modResults.contents = contents;
    return cfg;
  });

const withSceneDelegateFile = (config) =>
  withXcodeProject(config, (cfg) => {
    const projectName = cfg.modRequest.projectName;
    const relPath = `${projectName}/SceneDelegate.swift`;
    fs.writeFileSync(path.join(cfg.modRequest.platformProjectRoot, relPath), SCENE_DELEGATE);
    if (!cfg.modResults.hasFile(relPath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
        filepath: relPath,
        groupName: projectName,
        project: cfg.modResults,
      });
    }
    return cfg;
  });

module.exports = function withSceneLifecycle(config) {
  config = withSceneManifest(config);
  config = withAppDelegateWithoutWindow(config);
  config = withSceneDelegateFile(config);
  return config;
};
